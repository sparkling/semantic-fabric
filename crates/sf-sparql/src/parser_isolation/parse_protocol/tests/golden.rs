#[test]
fn request_has_an_independently_spelled_golden_vector() {
    let expected: [u8; REQUEST_HEADER_LEN + SAMPLE_SOURCE.len()] = [
        // Magic, protocol version, request kind, zero flags, 96-byte header.
        0x53, 0x46, 0x50, 0x52, 0x45, 0x51, 0x30, 0x31, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00,
        0x60, // Six source bytes, big endian.
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x06, // Nonce 0x00 through 0x1f.
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e,
        0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d,
        0x1e, 0x1f, // SHA-256("ASK {}").
        0x81, 0x9e, 0xa9, 0x1e, 0xd5, 0xf1, 0x2b, 0x38, 0xcc, 0xed, 0x06, 0x81, 0xc9, 0x3f, 0xbb,
        0x6a, 0x85, 0x04, 0x55, 0xb3, 0xd9, 0xfa, 0x51, 0x85, 0x2f, 0xfb, 0xa5, 0xf8, 0x5a, 0x5f,
        0x35, 0x5a, // UTF-8 tag, QueryV1 version, four reserved zero bytes.
        0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, // "ASK {}".
        0x41, 0x53, 0x4b, 0x20, 0x7b, 0x7d,
    ];
    let encoded = request(SAMPLE_SOURCE).encode().expect("request encodes");
    assert_eq!(encoded, expected);
    assert_eq!(
        ParseRequestV1::decode_exact(&expected)
            .expect("golden request decodes")
            .source(),
        SAMPLE_SOURCE
    );
}

#[test]
fn syntax_rejection_has_an_independently_spelled_golden_vector() {
    let expected: [u8; RESULT_HEADER_LEN] = [
        // Magic, protocol version, rejection kind, zero flags, 128-byte header.
        0x53, 0x46, 0x50, 0x52, 0x45, 0x53, 0x30, 0x31, 0x00, 0x01, 0x02, 0x00, 0x00, 0x00, 0x00,
        0x80, // No payload.
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // Nonce 0x00 through 0x1f.
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e,
        0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d,
        0x1e, 0x1f, // SHA-256("ASK {}").
        0x81, 0x9e, 0xa9, 0x1e, 0xd5, 0xf1, 0x2b, 0x38, 0xcc, 0xed, 0x06, 0x81, 0xc9, 0x3f, 0xbb,
        0x6a, 0x85, 0x04, 0x55, 0xb3, 0xd9, 0xfa, 0x51, 0x85, 0x2f, 0xfb, 0xa5, 0xf8, 0x5a, 0x5f,
        0x35, 0x5a, // SHA-256(empty payload).
        0xe3, 0xb0, 0xc4, 0x42, 0x98, 0xfc, 0x1c, 0x14, 0x9a, 0xfb, 0xf4, 0xc8, 0x99, 0x6f, 0xb9,
        0x24, 0x27, 0xae, 0x41, 0xe4, 0x64, 0x9b, 0x93, 0x4c, 0xa4, 0x95, 0x99, 0x1b, 0x78, 0x52,
        0xb8, 0x55, // No QueryV1 payload, closed syntax code, four reserved zero bytes.
        0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00,
    ];
    let encoded = rejection_bytes(SAMPLE_SOURCE, ParseRejectionV1::Syntax);
    assert_eq!(encoded, expected);
    let request = request(SAMPLE_SOURCE);
    let decoded =
        ParseResultV1::decode_exact_for(&expected, &request).expect("golden rejection decodes");
    assert_eq!(decoded.rejection(), Some(ParseRejectionV1::Syntax));

    let mut resource_expected = expected;
    resource_expected[RESULT_REJECTION_OFFSET..RESULT_REJECTION_OFFSET + 2]
        .copy_from_slice(&(ParseRejectionV1::ResourceExhausted as u16).to_be_bytes());
    assert_eq!(
        rejection_bytes(SAMPLE_SOURCE, ParseRejectionV1::ResourceExhausted),
        resource_expected
    );
    assert_eq!(
        ParseResultV1::encode_fixed_rejection_for(&request, ParseRejectionV1::ResourceExhausted),
        resource_expected
    );
    assert_eq!(
        ParseResultV1::decode_exact_for(&resource_expected, &request)
            .expect("golden resource rejection decodes")
            .rejection(),
        Some(ParseRejectionV1::ResourceExhausted)
    );
}

